import assert from "node:assert/strict";
import { registerHooks } from "node:module";
import { pathToFileURL } from "node:url";
import path from "node:path";

registerHooks({ resolve(specifier, context, nextResolve) {
  return nextResolve(specifier.startsWith("@/") ? pathToFileURL(path.resolve(specifier.slice(2) + ".ts")).href : specifier, context);
} });
const { buildProvisionReport, progressionLabel, reportCsv } = await import("../lib/provision.ts");
const { buildReportData, groupEntriesByYear } = await import("../lib/reporting.ts");
const { readAllRows } = await import("../lib/readAllRows.ts");
const { buildBundle } = await import("../lib/multiSchoolData.ts");
const framework = { id: "lit", name: "Literacy Framework", shortName: "Literacy", strands: [{ id: "s", name: "Writing", elements: [{ id: "e1", name: "Vocabulary" }, { id: "e2", name: "Punctuation" }] }] };
const theme = { id: "t", name: "Local contexts", active: true, elements: [{ id: "te", name: "Cynefin", active: true }] };
const reference = { frameworkId: "lit", framework: "Literacy Framework", strandId: "s", strand: "Writing", elementId: "e1", element: "Vocabulary", progressionStep: 3, progressionReference: "Step 3" };
const mapping = { id: "a", subject: "English", year: "Y7", term: "autumn", unit: "Local stories", activityDescription: "Write about the local community", schemeReference: "EN1", lastMappedDate: "2026-09-01", frameworkReferences: [reference, reference], crossCuttingThemeElementIds: ["te"] };
const mappings = [mapping, { ...mapping, id: "b", year: "Year 7", term: "Spring" }, { ...mapping, id: "c", subject: "History", year: "Year 12", term: "Summer", activityDescription: "", frameworkReferences: [] }];
const all = { subject: "", year: "", term: "" };
const report = buildProvisionReport(mappings, ["English", "History", "DT"], [framework], [theme], all);
assert.equal(report.entries.length, 3);
assert.equal(report.coverage[0].entries.length, 2, "Duplicate links must not inflate activity counts");
assert.equal(report.coverage[0].terms.length, 2);
assert.equal(report.unmapped.length, 1);
assert.equal(report.noEvidence[0].subject, "DT");
assert.equal(report.missingDescription.length, 1);
assert.equal(report.themeCoverage[0].elements[0].entries.length, 3);
assert.ok(report.years.includes("Year 12"));
assert.ok(groupEntriesByYear(report.entries).some((group) => group.year === "Year 12"));
const filtered = buildProvisionReport(mappings, ["English", "History"], [framework], [theme], { subject: "English", year: "Year 7", term: "Autumn" });
assert.equal(filtered.entries.length, 1);
assert.equal(filtered.coverage[0].entries.length, 1);
assert.equal(filtered.themeCoverage[0].entries.length, 1);
assert.equal(filtered.subjectRows[0].terms[0].entries.length, 1);
assert.equal(progressionLabel({ ...reference, progressionReference: "Step 3–4" }), "Bridging");
assert.equal(progressionLabel({}), "Unspecified");
const legacy = buildReportData([{ ...mapping, crossCuttingThemeIds: ["t"], crossCuttingThemes: ["Local contexts"] }], [theme]);
assert.equal(legacy.entries[0].themeItems.length, 1);
assert.equal(legacy.entries[0].themeItems[0].element, "Cynefin");
const empty = buildProvisionReport([], ["English"], [], [], all);
assert.equal(empty.coverage.length, 0);
assert.equal(empty.entries.length, 0);
assert.equal(empty.noEvidence.length, 1);
const csv = reportCsv([["=formula", 'a "quote", and\nnew line']]);
assert.ok(csv.includes("'=formula"));
assert.ok(csv.includes('"a ""quote"", and\nnew line"'));
const large = Array.from({ length: 1250 }, (_, id) => ({ id }));
const paged = await readAllRows({ range: async (from, to) => ({ data: large.slice(from, to + 1), error: null }) });
assert.equal(paged.data.length, 1250);
const failed = await readAllRows({ range: async (from) => from ? { data: null, error: { message: "failed" } } : { data: large.slice(0, 500), error: null } });
assert.equal(failed.data, null, "Partial data must not be treated as a complete report");
const bundle = buildBundle({ schoolId: "test", subjectConfigs: [], aoleConfigs: [], frameworkLibrary: [], crossCuttingThemes: [], mappings: [mapping] });
assert.equal(bundle.mappings[0].year, "Year 7");
assert.equal(bundle.mappings[0].term, "Autumn");
console.log("Passed: year/term normalisation, consistent filters, distinct counts, missing subjects/elements, theme resolution, bridging progression, CSV escaping and paginated loading.");
